# 4. LEARNED DYNAMICS MODEL
# ============================================================

class DynamicsNetwork(nn.Module):

    def __init__(self):

        super().__init__()

        self.network = nn.Sequential(
            nn.Linear(OBS_DIM + ACTION_DIM, 256),
            nn.ReLU(),

            nn.Linear(256, 256),
            nn.ReLU(),

            nn.Linear(256, OBS_DIM),
        )

    def forward(self, x):

        return self.network(x)


class DynamicsEnsemble:

    def __init__(self):

        self.models = [
            DynamicsNetwork().to(DEVICE)
            for _ in range(
                MODEL_ENSEMBLE_SIZE
            )
        ]

        self.optimizers = [
            optim.Adam(
                model.parameters(),
                lr=MODEL_LR,
            )
            for model in self.models
        ]

        self.input_mean = None
        self.input_std = None

        self.output_mean = None
        self.output_std = None

        self.loss_history = []

        self.ready = False

    @staticmethod
    def transition_features(
        states,
        actions,
    ):

        return np.concatenate(
            [
                states,
                actions,
            ],
            axis=1,
        )

    def fit(
        self,
        real_buffer,
        epochs=MODEL_EPOCHS,
    ):

        if len(real_buffer) < 100:

            print(
                "Not enough real transitions to train model."
            )

            return

        states, actions, _, next_states, _ = (
            real_buffer.sample(
                min(
                    len(real_buffer),
                    30000,
                )
            )
        )

        inputs = self.transition_features(
            states,
            actions,
        )

        # Learn the observation delta.
        outputs = (
            next_states - states
        )

        self.input_mean = inputs.mean(
            axis=0
        )

        self.input_std = np.maximum(
            inputs.std(axis=0),
            1e-5,
        )

        self.output_mean = outputs.mean(
            axis=0
        )

        self.output_std = np.maximum(
            outputs.std(axis=0),
            1e-5,
        )

        normalized_inputs = (
            inputs - self.input_mean
        ) / self.input_std

        normalized_outputs = (
            outputs - self.output_mean
        ) / self.output_std

        x = torch.as_tensor(
            normalized_inputs,
            dtype=torch.float32,
            device=DEVICE,
        )

        y = torch.as_tensor(
            normalized_outputs,
            dtype=torch.float32,
            device=DEVICE,
        )

        losses = []

        for model_index, model in enumerate(
            self.models
        ):

            optimizer = self.optimizers[
                model_index
            ]

            model_losses = []

            # Bootstrap resampling gives each ensemble member
            # a slightly different view of the real dataset.
            indices = torch.randint(
                0,
                len(x),
                (len(x),),
                device=DEVICE,
            )

            model_x = x[indices]
            model_y = y[indices]

            for _ in range(epochs):

                permutation = torch.randperm(
                    len(model_x),
                    device=DEVICE,
                )

                epoch_losses = []

                for start in range(
                    0,
                    len(model_x),
                    MODEL_BATCH_SIZE,
                ):

                    batch_indices = permutation[
                        start:start + MODEL_BATCH_SIZE
                    ]

                    batch_x = model_x[
                        batch_indices
                    ]

                    batch_y = model_y[
                        batch_indices
                    ]

                    prediction = model(
                        batch_x
                    )

                    loss = F.mse_loss(
                        prediction,
                        batch_y,
                    )

                    optimizer.zero_grad()

                    loss.backward()

                    nn.utils.clip_grad_norm_(
                        model.parameters(),
                        5.0,
                    )

                    optimizer.step()

                    epoch_losses.append(
                        loss.item()
                    )

                model_losses.append(
                    float(
                        np.mean(epoch_losses)
                    )
                )

            losses.append(
                float(
                    np.mean(model_losses)
                )
            )

        self.loss_history.append(
            float(np.mean(losses))
        )

        self.ready = True

        print(
            "Dynamics ensemble trained | "
            f"mean normalized loss={np.mean(losses):.6f}"
        )

    def predict_all(
        self,
        states,
        actions,
    ):

        if not self.ready:

            raise RuntimeError(
                "Dynamics model has not been trained."
            )

        inputs = self.transition_features(
            states,
            actions,
        )

        normalized_inputs = (
            inputs - self.input_mean
        ) / self.input_std

        x = torch.as_tensor(
            normalized_inputs,
            dtype=torch.float32,
            device=DEVICE,
        )

        predictions = []

        with torch.no_grad():

            for model in self.models:

                normalized_delta = model(
                    x
                ).cpu().numpy()

                delta = (
                    normalized_delta
                    * self.output_std
                    + self.output_mean
                )

                predictions.append(
                    states + delta
                )

        return np.stack(
            predictions,
            axis=0,
        )

    def predict(
        self,
        states,
        actions,
    ):

        predictions = self.predict_all(
            states,
            actions,
        )

        mean_prediction = predictions.mean(
            axis=0
        )

        disagreement = np.mean(
            np.linalg.norm(
                predictions - mean_prediction[None, :, :],
                axis=-1,
            ),
            axis=0,
        )

        return (
            mean_prediction.astype(np.float32),
            disagreement.astype(np.float32),
        )


