def evaluate_policy(
    agent,
    episodes=5,
):

    env = DroneEnv()

    returns = []
    distances = []
    collisions = []

    for episode in range(episodes):

        observation = env.reset()

        total_return = 0.0
        episode_distances = []

        collision_count = 0

        for _ in range(
            EPISODE_STEPS
        ):

            action = agent.select_action(
                observation,
                deterministic=True,
            )

            (
                next_observation,
                reward,
                terminated,
                truncated,
                info,
            ) = env.step(
                action
            )

            total_return += reward

            episode_distances.append(
                info["distance"]
            )

            if info["collision"]:

                collision_count += 1

            observation = next_observation

            if terminated or truncated:

                break

        returns.append(
            total_return
        )

        distances.append(
            np.mean(
                episode_distances
            )
        )

        collisions.append(
            collision_count
        )

    result = {
        "mean_return": float(
            np.mean(returns)
        ),

        "mean_distance": float(
            np.mean(distances)
        ),

        "mean_collision_steps": float(
            np.mean(collisions)
        ),
    }

    print(
        "\nEvaluation:"
    )

    for key, value in result.items():

        print(
            f"{key}: {value:.3f}"
        )

    return result


