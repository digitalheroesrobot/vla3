# 6. TWIN CRITICS
# ============================================================

class Critic(nn.Module):

    def __init__(self):

        super().__init__()

        self.q1 = nn.Sequential(
            nn.Linear(
                OBS_DIM + ACTION_DIM,
                256,
            ),
            nn.ReLU(),

            nn.Linear(256, 256),
            nn.ReLU(),

            nn.Linear(256, 1),
        )

        self.q2 = nn.Sequential(
            nn.Linear(
                OBS_DIM + ACTION_DIM,
                256,
            ),
            nn.ReLU(),

            nn.Linear(256, 256),
            nn.ReLU(),

            nn.Linear(256, 1),
        )

    def forward(
        self,
        state,
        action,
    ):

        x = torch.cat(
            [
                state,
                action,
            ],
            dim=-1,
        )

        return (
            self.q1(x),
            self.q2(x),
        )


# ============================================================
# 7. SAC AGENT
# ============================================================

class SACAgent:

    def __init__(self):

        self.actor = Actor().to(
            DEVICE
        )

        self.critic = Critic().to(
            DEVICE
        )

        self.target_critic = Critic().to(
            DEVICE
        )

        self.target_critic.load_state_dict(
            self.critic.state_dict()
        )

        self.actor_optimizer = optim.Adam(
            self.actor.parameters(),
            lr=SAC_LR,
        )

        self.critic_optimizer = optim.Adam(
            self.critic.parameters(),
            lr=SAC_LR,
        )

        self.log_alpha = torch.tensor(
            math.log(ALPHA_INITIAL),
            dtype=torch.float32,
            device=DEVICE,
            requires_grad=True,
        )

        self.alpha_optimizer = optim.Adam(
            [self.log_alpha],
            lr=SAC_LR,
        )

        self.target_entropy = -float(
            ACTION_DIM
        )

        self.update_count = 0

    @property
    def alpha(self):

        return self.log_alpha.exp()

    def select_action(
        self,
        observation,
        deterministic=False,
    ):

        state = torch.as_tensor(
            observation,
            dtype=torch.float32,
            device=DEVICE,
        ).unsqueeze(0)

        with torch.no_grad():

            if deterministic:

                action = self.actor.deterministic_action(
                    state
                )

            else:

                action, _ = self.actor.sample(
                    state
                )

        return action.squeeze(0).cpu().numpy()

    def update(
        self,
        batch,
    ):

        (
            states,
            actions,
            rewards,
            next_states,
            dones,
        ) = batch

        states = torch.as_tensor(
            states,
            dtype=torch.float32,
            device=DEVICE,
        )

        actions = torch.as_tensor(
            actions,
            dtype=torch.float32,
            device=DEVICE,
        )

        rewards = torch.as_tensor(
            rewards,
            dtype=torch.float32,
            device=DEVICE,
        )

        next_states = torch.as_tensor(
            next_states,
            dtype=torch.float32,
            device=DEVICE,
        )

        dones = torch.as_tensor(
            dones,
            dtype=torch.float32,
            device=DEVICE,
        )

        # --------------------------------------------
        # Critic update
        # --------------------------------------------

        with torch.no_grad():

            next_actions, next_log_probability = (
                self.actor.sample(
                    next_states
                )
            )

            target_q1, target_q2 = (
                self.target_critic(
                    next_states,
                    next_actions,
                )
            )

            target_q = torch.minimum(
                target_q1,
                target_q2,
            )

            target_value = (
                target_q
                - self.alpha.detach()
                * next_log_probability
            )

            # Only true termination suppresses bootstrapping.
            y = (
                rewards
                + GAMMA
                * (1.0 - dones)
                * target_value
            )

        current_q1, current_q2 = (
            self.critic(
                states,
                actions,
            )
        )

        critic_loss = (
            F.mse_loss(
                current_q1,
                y,
            )
            + F.mse_loss(
                current_q2,
                y,
            )
        )

        self.critic_optimizer.zero_grad()

        critic_loss.backward()

        nn.utils.clip_grad_norm_(
            self.critic.parameters(),
            10.0,
        )

        self.critic_optimizer.step()

        # --------------------------------------------
        # Actor update
        # --------------------------------------------

        new_actions, log_probability = (
            self.actor.sample(
                states
            )
        )

        q1_pi, q2_pi = self.critic(
            states,
            new_actions,
        )

        min_q_pi = torch.minimum(
            q1_pi,
            q2_pi,
        )

        actor_loss = (
            self.alpha.detach()
            * log_probability
            - min_q_pi
        ).mean()

        self.actor_optimizer.zero_grad()

        actor_loss.backward()

        nn.utils.clip_grad_norm_(
            self.actor.parameters(),
            10.0,
        )

        self.actor_optimizer.step()

        # --------------------------------------------
        # Automatic entropy temperature
        # --------------------------------------------

        alpha_loss = -(
            self.log_alpha
            * (
                log_probability.detach()
                + self.target_entropy
            )
        ).mean()

        self.alpha_optimizer.zero_grad()

        alpha_loss.backward()

        self.alpha_optimizer.step()

        # --------------------------------------------
        # Target critic soft update
        # --------------------------------------------

        with torch.no_grad():

            for parameter, target_parameter in zip(
                self.critic.parameters(),
                self.target_critic.parameters(),
            ):

                target_parameter.data.mul_(
                    1.0 - TAU
                )

                target_parameter.data.add_(
                    TAU * parameter.data
                )

        self.update_count += 1

        return {
            "critic_loss": float(
                critic_loss.detach().cpu()
            ),

            "actor_loss": float(
                actor_loss.detach().cpu()
            ),

            "alpha": float(
                self.alpha.detach().cpu()
            ),
        }


