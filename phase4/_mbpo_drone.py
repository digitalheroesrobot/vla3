# 5. ACTOR NETWORK
# ============================================================

LOG_STD_MIN = -5.0
LOG_STD_MAX = 2.0


class Actor(nn.Module):

    def __init__(self):

        super().__init__()

        self.backbone = nn.Sequential(
            nn.Linear(OBS_DIM, 256),
            nn.ReLU(),

            nn.Linear(256, 256),
            nn.ReLU(),
        )

        self.mean = nn.Linear(
            256,
            ACTION_DIM,
        )

        self.log_std = nn.Linear(
            256,
            ACTION_DIM,
        )

    def forward(self, state):

        features = self.backbone(
            state
        )

        mean = self.mean(
            features
        )

        log_std = self.log_std(
            features
        )

        log_std = torch.clamp(
            log_std,
            LOG_STD_MIN,
            LOG_STD_MAX,
        )

        return mean, log_std

    def sample(self, state):

        mean, log_std = self.forward(
            state
        )

        std = log_std.exp()

        distribution = torch.distributions.Normal(
            mean,
            std,
        )

        raw_action = distribution.rsample()

        action = torch.tanh(
            raw_action
        )

        # Correct log probability for tanh squashing.
        log_probability = distribution.log_prob(
            raw_action
        )

        log_probability -= torch.log(
            1.0 - action.pow(2) + 1e-6
        )

        log_probability = log_probability.sum(
            dim=-1,
            keepdim=True,
        )

        return (
            action,
            log_probability,
        )

    def deterministic_action(self, state):

        mean, _ = self.forward(
            state
        )

        return torch.tanh(
            mean
        )


