# 2. DRONE ENVIRONMENT
# ============================================================

def clip_state(state):

    state = np.asarray(
        state,
        dtype=np.float32,
    ).copy()

    speed = np.linalg.norm(
        state[2:4]
    )

    if speed > MAX_SPEED:

        state[2:4] *= (
            MAX_SPEED / (speed + 1e-9)
        )

    state[0] = np.clip(
        state[0],
        DRONE_RADIUS,
        WORLD_W - DRONE_RADIUS,
    )

    state[1] = np.clip(
        state[1],
        DRONE_RADIUS,
        WORLD_H - DRONE_RADIUS,
    )

    return state


def drone_transition(
    state,
    action,
):

    action = np.clip(
        np.asarray(
            action,
            dtype=np.float32,
        ),
        -1.0,
        1.0,
    )

    velocity = state[2:4]

    acceleration = (
        MOTOR_GAIN * MAX_ACCEL * action
        - LINEAR_DRAG * velocity
        - QUADRATIC_DRAG
        * np.abs(velocity)
        * velocity
        + WIND
    )

    next_velocity = (
        velocity + acceleration * DT
    )

    next_position = (
        state[:2] + next_velocity * DT
    )

    return clip_state(
        np.concatenate(
            [
                next_position,
                next_velocity,
            ]
        )
    )


class DroneEnv:

    def __init__(self):

        self.target = MovingTarget(
            [710.0, 315.0]
        )

        self.state = None
        self.steps = 0

        self.reset()

    def observation(self):

        position = self.state[:2]

        velocity = self.state[2:4]

        target_position = (
            self.target.position()
        )

        target_velocity = (
            self.target.velocity()
        )

        relative_target = (
            target_position - position
        )

        relative_obstacle = (
            OBSTACLE - position
        )

        phase_features = np.array(
            [
                math.sin(self.target.phase),
                math.cos(self.target.phase),
            ],
            dtype=np.float32,
        )

        return np.concatenate(
            [
                relative_target / 400.0,
                target_velocity / 200.0,
                velocity / MAX_SPEED,
                relative_obstacle / 400.0,
                phase_features,
            ]
        ).astype(
            np.float32
        )

    def reset(self):

        self.state = np.array(
            [
                110.0,
                500.0,
                0.0,
                0.0,
            ],
            dtype=np.float32,
        )

        self.target.phase = np.random.uniform(
            0.0,
            2.0 * math.pi,
        )

        self.steps = 0

        return self.observation()

    def step(self, action):

        old_position = self.state[:2].copy()

        # The target moves during this transition.
        future_phase = (
            self.target.phase
            + TARGET_OMEGA * DT
        )

        future_target = self.target.position(
            future_phase
        )

        distance_before = np.linalg.norm(
            old_position - future_target
        )

        self.state = drone_transition(
            self.state,
            action,
        )

        self.target.advance()

        distance_after = np.linalg.norm(
            self.state[:2] - self.target.position()
        )

        progress = (
            distance_before - distance_after
        )

        obstacle_distance = np.linalg.norm(
            self.state[:2] - OBSTACLE
        )

        collision = (
            obstacle_distance < OBSTACLE_RADIUS
        )

        boundary_distance = min(
            self.state[0],
            WORLD_W - self.state[0],
            self.state[1],
            WORLD_H - self.state[1],
        )

        reward = (
            0.04 * progress
            - 0.015 * distance_after
            - 0.15 * np.sum(
                np.asarray(action) ** 2
            )
        )

        # Soft obstacle penalty.
        obstacle_violation = max(
            0.0,
            SAFE_RADIUS - obstacle_distance,
        )

        reward -= (
            0.008 * obstacle_violation**2
        )

        # Boundary penalty.
        boundary_violation = max(
            0.0,
            55.0 - boundary_distance,
        )

        reward -= (
            0.015 * boundary_violation**2
        )

        if collision:

            reward -= 80.0

        self.steps += 1

        terminated = (
            collision
        )

        truncated = (
            self.steps >= EPISODE_STEPS
        )

        return (
            self.observation(),
            float(reward),
            terminated,
            truncated,
            {
                "distance": float(
                    distance_after
                ),
                "collision": collision,
            },
        )


