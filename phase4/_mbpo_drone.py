class ReplayBuffer:

    def __init__(
        self,
        capacity=REPLAY_CAPACITY,
    ):

        self.buffer = deque(
            maxlen=capacity
        )

    def add(
        self,
        state,
        action,
        reward,
        next_state,
        terminated,
    ):

        self.buffer.append(
            (
                np.asarray(
                    state,
                    dtype=np.float32,
                ).copy(),

                np.asarray(
                    action,
                    dtype=np.float32,
                ).copy(),

                float(reward),

                np.asarray(
                    next_state,
                    dtype=np.float32,
                ).copy(),

                float(terminated),
            )
        )

    def sample(self, batch_size):

        batch = random.sample(
            self.buffer,
            batch_size,
        )

        states, actions, rewards, next_states, dones = (
            zip(*batch)
        )

        return (
            np.asarray(states, dtype=np.float32),
            np.asarray(actions, dtype=np.float32),
            np.asarray(rewards, dtype=np.float32).reshape(-1, 1),
            np.asarray(next_states, dtype=np.float32),
            np.asarray(dones, dtype=np.float32).reshape(-1, 1),
        )

    def __len__(self):

        return len(self.buffer)


