# 8. SYNTHETIC EXPERIENCE GENERATION
# ============================================================

def generate_synthetic_rollouts(
    env,
    agent,
    model,
    real_buffer,
    synthetic_buffer,
    starts=SYNTHETIC_STARTS,
    horizon=SYNTHETIC_ROLLOUT_HORIZON,
):

    """
    Start synthetic rollouts from real replay states.

    This is important:
        We do not start every synthetic rollout from an
        arbitrary state distribution.

    Short rollouts reduce accumulated model error.

    The target phase is included in the observation.
    Its phase update is therefore part of the learned
    transition dynamics.
    """

    if (
        len(real_buffer) < 100
        or not model.ready
    ):

        return 0

    initial_batch = real_buffer.sample(
        min(
            starts,
            len(real_buffer),
        )
    )

    (
        initial_states,
        _,
        _,
        _,
        _,
    ) = initial_batch

    states = initial_states.copy()

    accepted = 0

    for _ in range(horizon):

        actions = np.asarray(
            [
                agent.select_action(
                    state,
                    deterministic=False,
                )
                for state in states
            ],
            dtype=np.float32,
        )

        predicted_states, uncertainty = (
            model.predict(
                states,
                actions,
            )
        )

        # Discard predictions with high ensemble disagreement.
        valid = (
            uncertainty
            < SYNTHETIC_MAX_UNCERTAINTY
        )

        for index in np.where(valid)[0]:

            current = states[index]

            next_state = predicted_states[
                index
            ]

            # Observation coordinates are normalized.
            # Convert relative target and obstacle features
            # into an approximate geometric safety measure.
            relative_obstacle = (
                current[6:8] * 400.0
            )

            relative_target = (
                current[0:2] * 400.0
            )

            predicted_relative_obstacle = (
                next_state[6:8] * 400.0
            )

            predicted_relative_target = (
                next_state[0:2] * 400.0
            )

            obstacle_distance = np.linalg.norm(
                predicted_relative_obstacle
            )

            target_distance_before = np.linalg.norm(
                relative_target
            )

            target_distance_after = np.linalg.norm(
                predicted_relative_target
            )

            reward = (
                0.04
                * (
                    target_distance_before
                    - target_distance_after
                )
                - 0.015
                * target_distance_after
                - 0.15
                * np.sum(
                    actions[index] ** 2
                )
            )

            obstacle_violation = max(
                0.0,
                SAFE_RADIUS - obstacle_distance,
            )

            reward -= (
                0.008
                * obstacle_violation**2
            )

            # Predicted termination is only a rough approximation.
            terminated = (
                obstacle_distance
                < OBSTACLE_RADIUS
            )

            synthetic_buffer.add(
                current,
                actions[index],
                reward,
                next_state,
                terminated,
            )

            accepted += 1

        # Only accepted model predictions continue the rollout.
        if not np.any(valid):

            break

        states = predicted_states[
            valid
        ]

        if len(states) == 0:

            break

    return accepted


