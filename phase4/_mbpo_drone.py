def train_mbpo():

    env = DroneEnv()

    agent = SACAgent()

    real_buffer = ReplayBuffer()

    synthetic_buffer = ReplayBuffer(
        MAX_SYNTHETIC_TRANSITIONS
    )

    model = DynamicsEnsemble()

    episode_returns = []
    episode_distances = []

    model_training_losses = []

    total_steps = 0

    for episode in range(
        TRAIN_EPISODES
    ):

        observation = env.reset()

        episode_return = 0.0
        episode_distance = []

        for step in range(
            EPISODE_STEPS
        ):

            if total_steps < INITIAL_RANDOM_STEPS:

                action = np.random.uniform(
                    -1.0,
                    1.0,
                    size=ACTION_DIM,
                ).astype(
                    np.float32
                )

            else:

                action = agent.select_action(
                    observation,
                    deterministic=False,
                )

            (
                next_observation,
                reward,
                terminated,
                truncated,
                info,
            ) = env.step(
                action
            )

            real_buffer.add(
                observation,
                action,
                reward,
                next_observation,
                terminated,
            )

            episode_return += reward

            episode_distance.append(
                info["distance"]
            )

            observation = next_observation

            total_steps += 1

            # ----------------------------------------
            # Dynamics model training
            # ----------------------------------------

            if (
                len(real_buffer)
                >= WARMUP_MODEL_TRANSITIONS
                and total_steps
                % (
                    MODEL_TRAIN_INTERVAL
                    * EPISODE_STEPS
                )
                == 0
            ):

                print(
                    f"\nTraining model at step {total_steps}"
                )

                model.fit(
                    real_buffer
                )

                if model.loss_history:

                    model_training_losses.append(
                        model.loss_history[-1]
                    )

            # ----------------------------------------
            # Synthetic experience generation
            # ----------------------------------------

            if (
                model.ready
                and total_steps
                % (
                    SYNTHETIC_INTERVAL
                    * EPISODE_STEPS
                )
                == 0
            ):

                accepted = generate_synthetic_rollouts(
                    env,
                    agent,
                    model,
                    real_buffer,
                    synthetic_buffer,
                )

                print(
                    "Synthetic transitions accepted:",
                    accepted,
                )

            # ----------------------------------------
            # SAC updates
            # ----------------------------------------

            if (
                len(real_buffer) >= BATCH_SIZE
                and total_steps >= INITIAL_RANDOM_STEPS
            ):

                for _ in range(
                    UPDATES_PER_STEP
                ):

                    real_batch = real_buffer.sample(
                        BATCH_SIZE
                    )

                    if (
                        model.ready
                        and len(synthetic_buffer) >= BATCH_SIZE
                    ):

                        # Mix real and synthetic data.
                        # 50% real, 50% synthetic.
                        synthetic_batch = (
                            synthetic_buffer.sample(
                                BATCH_SIZE // 2
                            )
                        )

                        real_half = real_buffer.sample(
                            BATCH_SIZE // 2
                        )

                        batch = tuple(
                            np.concatenate(
                                [
                                    real_half[index],
                                    synthetic_batch[index],
                                ],
                                axis=0,
                            )
                            for index in range(5)
                        )

                    else:

                        batch = real_batch

                    agent.update(
                        batch
                    )

            if terminated or truncated:

                break

        mean_distance = float(
            np.mean(
                episode_distance
            )
        )

        episode_returns.append(
            episode_return
        )

        episode_distances.append(
            mean_distance
        )

        print(
            f"Episode {episode + 1:3d}/{TRAIN_EPISODES}"
            f" | Return={episode_return:9.2f}"
            f" | Distance={mean_distance:8.2f}"
            f" | Real={len(real_buffer):6d}"
            f" | Synthetic={len(synthetic_buffer):6d}"
            f" | Alpha={float(agent.alpha.detach().cpu()):.3f}"
        )

    return (
        agent,
        model,
        real_buffer,
        synthetic_buffer,
        {
            "returns": episode_returns,
            "distances": episode_distances,
            "model_losses": model_training_losses,
        },
    )


