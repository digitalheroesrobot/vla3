@dataclass
class ExperimentResult:

    ordinary: float

    weighted: float

    per_decision: float

    on_policy: float

    exact: float

    effective_sample_size: float

    ordinary_details: dict

    weighted_details: dict


# ================================================================
# 16. RUN COMPARISON EXPERIMENT
# ================================================================

def run_experiment(
    num_episodes=NUM_EPISODES,
    seed=SEED,
):
    """
    Compare four estimators:

        1. Ordinary IS.
        2. Weighted IS.
        3. Per-decision IS.
        4. Direct on-policy Monte Carlo.
    """

    dataset = generate_dataset(
        num_episodes=num_episodes,
        seed=seed,
    )

    ordinary = ordinary_importance_sampling(
        dataset
    )

    weighted = weighted_importance_sampling(
        dataset
    )

    per_decision = per_decision_importance_sampling(
        dataset
    )

    on_policy = on_policy_monte_carlo(
        num_episodes=num_episodes,
        seed=seed + 1,
    )

    exact = exact_target_value()

    ess = effective_sample_size(
        ordinary["ratios"]
    )

    return ExperimentResult(
        ordinary=ordinary["estimate"],
        weighted=weighted["estimate"],
        per_decision=per_decision["estimate"],
        on_policy=on_policy,
        exact=exact,
        effective_sample_size=ess,
        ordinary_details=ordinary,
        weighted_details=weighted,
    )


# ================================================================
# 17. SAMPLE-SIZE CONVERGENCE EXPERIMENT
# ================================================================

def run_convergence_experiment(
    sample_sizes=SAMPLE_SIZES,
    num_runs=NUM_RUNS,
    seed=SEED,
):
    """
    Compare estimator behavior at increasing dataset sizes.

    Each run creates an independent behavior-policy dataset.
    """

    methods = [
        "ordinary",
        "weighted",
        "per_decision",
        "on_policy",
    ]

    results = {
        method: {
            "mean": [],
            "std": [],
            "errors": [],
        }
        for method in methods
    }

    exact = exact_target_value()

    for sample_size in sample_sizes:

        run_values = {
            method: []
            for method in methods
        }

        for run_index in range(num_runs):

            result = run_experiment(
                num_episodes=sample_size,
                seed=seed + run_index * 1000,
            )

            run_values["ordinary"].append(
                result.ordinary
            )

            run_values["weighted"].append(
                result.weighted
            )

            run_values["per_decision"].append(
                result.per_decision
            )

            run_values["on_policy"].append(
                result.on_policy
            )

        for method in methods:

            values = np.asarray(
                run_values[method]
            )

            results[method]["mean"].append(
                float(np.mean(values))
            )

            results[method]["std"].append(
                float(np.std(values))
            )

            results[method]["errors"].append(
                float(
                    np.mean(
                        (values - exact) ** 2
                    )
                )
            )

    return {
        "sample_sizes": np.asarray(
            sample_sizes
        ),
        "methods": results,
        "exact": exact,
    }


