from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import matplotlib.pyplot as plt


# ================================================================
# 1. CONFIGURATION
# ================================================================

SEED = 42

HORIZON = 3

GAMMA = 0.95

BEHAVIOR_P_ACTION_1 = 0.50

TARGET_P_ACTION_1 = 0.80

NUM_EPISODES = 10000

NUM_RUNS = 30

SAMPLE_SIZES = [
    10,
    50,
    100,
    500,
    1000,
    5000,
    10000,
]


# ================================================================
# 2. POLICY DEFINITIONS
# ================================================================

def behavior_policy(action):
    """
    Behavior policy b(a).

    P(action=1) = 0.5
    P(action=0) = 0.5
    """

    if action == 1:
        return BEHAVIOR_P_ACTION_1

    if action == 0:
        return 1.0 - BEHAVIOR_P_ACTION_1

    raise ValueError("Invalid action.")


def target_policy(action):
    """
    Target policy pi(a).

    P(action=1) = 0.8
    P(action=0) = 0.2
    """

    if action == 1:
        return TARGET_P_ACTION_1

    if action == 0:
        return 1.0 - TARGET_P_ACTION_1

    raise ValueError("Invalid action.")


def policy_probabilities(p_action_1):
    """
    Convert probability of action 1 into:

        [P(action=0), P(action=1)]
    """

    if not 0.0 <= p_action_1 <= 1.0:
        raise ValueError(
            "Policy probability must be in [0, 1]."
        )

    return np.array([
        1.0 - p_action_1,
        p_action_1,
    ])


# ================================================================
# 3. IMPORTANCE SAMPLING RATIO
# ================================================================

def importance_ratio(
    target_probability,
    behavior_probability,
):
    """
    Calculate:

        rho = pi(a|s) / b(a|s)

    Cases:

        target > 0, behavior > 0:
            Return target / behavior.

        target = 0, behavior > 0:
            Return 0.

        target > 0, behavior = 0:
            Invalid support condition.

        target = 0, behavior = 0:
            The observed action is impossible under behavior.
            Raise an error.

    The function expects probabilities of an observed action.
    """

    if not 0.0 <= target_probability <= 1.0:
        raise ValueError(
            "Target probability must be in [0, 1]."
        )

    if not 0.0 <= behavior_probability <= 1.0:
        raise ValueError(
            "Behavior probability must be in [0, 1]."
        )

    if behavior_probability == 0.0:

        if target_probability > 0.0:
            raise ValueError(
                "Support violation: target policy assigns "
                "positive probability to an action that "
                "the behavior policy never selects."
            )

        raise ValueError(
            "Observed action has zero behavior probability."
        )

    return (
        target_probability / behavior_probability
    )


# ================================================================
# 4. TRAJECTORY IMPORTANCE RATIO
# ================================================================

def trajectory_importance_ratio(
    actions,
    target_probabilities,
    behavior_probabilities,
):
    """
    Calculate the product of per-step importance ratios.

        rho_trajectory = product[t] pi(A_t|S_t)/b(A_t|S_t)

    The experiment uses a stationary policy, so action
    probabilities are independent of state and time.

    The function accepts explicit per-step probabilities
    to make the calculation easy to test and reuse.
    """

    if not (
        len(actions)
        == len(target_probabilities)
        == len(behavior_probabilities)
    ):
        raise ValueError(
            "Actions and probability arrays must have equal length."
        )

    ratio = 1.0

    for target_p, behavior_p in zip(
        target_probabilities,
        behavior_probabilities,
    ):

        ratio *= importance_ratio(
            target_p,
            behavior_p,
        )

    return float(ratio)


def calculate_episode_importance_ratio(
    actions,
    target_p_action_1=TARGET_P_ACTION_1,
    behavior_p_action_1=BEHAVIOR_P_ACTION_1,
):
    """
    Calculate the complete trajectory ratio for the
    stationary binary-action policies used in this lesson.
    """

    target_probs = []

    behavior_probs = []

    for action in actions:

        target_probs.append(
            policy_probabilities(
                target_p_action_1
            )[action]
        )

        behavior_probs.append(
            policy_probabilities(
                behavior_p_action_1
            )[action]
        )

    return trajectory_importance_ratio(
        actions,
        target_probs,
        behavior_probs,
    )


# ================================================================
# 5. ENVIRONMENT
# ================================================================

@dataclass
class Trajectory:

    actions: list[int]

    rewards: list[float]

    @property
    def length(self):
        return len(self.actions)

    @property
    def discounted_return(self):
        return float(
            sum(
                (GAMMA ** t) * reward
                for t, reward in enumerate(self.rewards)
            )
        )


class FiniteHorizonEnvironment:
    """
    Three-step environment.

    Action 0:
        Reward = 1 with probability 0.2.

    Action 1:
        Reward = 1 with probability 0.8.

    Otherwise reward = 0.

    The episode ends after HORIZON decisions.
    """

    def __init__(self, seed=None):

        self.rng = np.random.default_rng(seed)

        self.time_step = 0

    def reset(self):

        self.time_step = 0

        return self.time_step

    def step(self, action):

        if self.time_step >= HORIZON:
            raise RuntimeError(
                "Episode already terminated."
            )

        if action not in (0, 1):
            raise ValueError(
                "Action must be 0 or 1."
            )

        reward_probability = (
            0.2 if action == 0 else 0.8
        )

        reward = float(
            self.rng.random() < reward_probability
        )

        self.time_step += 1

        terminated = (
            self.time_step >= HORIZON
        )

        return (
            self.time_step,
            reward,
            terminated,
        )


# ================================================================
# 6. GENERATE TRAJECTORY USING BEHAVIOR POLICY
# ================================================================

def generate_trajectory(
    env,
    behavior_p_action_1=BEHAVIOR_P_ACTION_1,
):
    """
    Collect one trajectory under the behavior policy.

    The target policy is not used to generate data.
    """

    action_probs = policy_probabilities(
        behavior_p_action_1
    )

    env.reset()

    actions = []

    rewards = []

    terminated = False

    while not terminated:

        action = int(
            env.rng.choice(
                [0, 1],
                p=action_probs,
            )
        )

        _, reward, terminated = env.step(
            action
        )

        actions.append(action)

        rewards.append(reward)

    return Trajectory(
        actions=actions,
        rewards=rewards,
    )


def generate_dataset(
    num_episodes,
    seed=SEED,
    behavior_p_action_1=BEHAVIOR_P_ACTION_1,
):
    """
    Generate a dataset containing trajectories sampled
    from the behavior policy.
    """

    if num_episodes <= 0:
        raise ValueError(
            "num_episodes must be positive."
        )

    env = FiniteHorizonEnvironment(
        seed=seed
    )

    dataset = []

    for _ in range(num_episodes):

        trajectory = generate_trajectory(
            env,
            behavior_p_action_1,
        )

        dataset.append(trajectory)

    return dataset


# ================================================================
# 7. DISCOUNTED RETURN
# ================================================================

def calculate_discounted_return(
    rewards,
    gamma=GAMMA,
):
    """
    G = R0 + gamma*R1 + gamma^2*R2 + ...

    This lesson indexes rewards from zero.
    """

    if not 0.0 <= gamma <= 1.0:
        raise ValueError(
            "gamma must be in [0, 1]."
        )

    return float(
        sum(
            (gamma ** t) * reward
            for t, reward in enumerate(rewards)
        )
    )


# ================================================================
# 8. ORDINARY IMPORTANCE SAMPLING
# ================================================================

def ordinary_importance_sampling(
    dataset,
    target_p_action_1=TARGET_P_ACTION_1,
    behavior_p_action_1=BEHAVIOR_P_ACTION_1,
    gamma=GAMMA,
):
    """
    Ordinary Importance Sampling:

        V_ordinary =
            (1/N) * sum[i] rho_i * G_i

    The estimator is unbiased when:
        1. The behavior policy covers the target policy.
        2. Trajectories are sampled from the behavior policy.
        3. The probability model is correct.
    """

    if len(dataset) == 0:
        raise ValueError(
            "Dataset cannot be empty."
        )

    weighted_returns = []

    ratios = []

    for trajectory in dataset:

        ratio = calculate_episode_importance_ratio(
            trajectory.actions,
            target_p_action_1,
            behavior_p_action_1,
        )

        G = calculate_discounted_return(
            trajectory.rewards,
            gamma,
        )

        ratios.append(ratio)

        weighted_returns.append(
            ratio * G
        )

    estimate = np.mean(
        weighted_returns
    )

    return {
        "estimate": float(estimate),
        "ratios": np.asarray(ratios),
        "weighted_returns": np.asarray(
            weighted_returns
        ),
    }


# ================================================================
# 9. WEIGHTED IMPORTANCE SAMPLING
# ================================================================

def weighted_importance_sampling(
    dataset,
    target_p_action_1=TARGET_P_ACTION_1,
    behavior_p_action_1=BEHAVIOR_P_ACTION_1,
    gamma=GAMMA,
):
    """
    Weighted Importance Sampling:

        V_weighted =
            sum[i] rho_i * G_i
            ------------------
                sum[i] rho_i

    WIS normalizes importance weights.

    It is generally biased for finite samples but
    consistent under suitable conditions.

    It often has lower variance than ordinary IS.
    """

    if len(dataset) == 0:
        raise ValueError(
            "Dataset cannot be empty."
        )

    ratios = []

    weighted_returns = []

    for trajectory in dataset:

        ratio = calculate_episode_importance_ratio(
            trajectory.actions,
            target_p_action_1,
            behavior_p_action_1,
        )

        G = calculate_discounted_return(
            trajectory.rewards,
            gamma,
        )

        ratios.append(ratio)

        weighted_returns.append(
            ratio * G
        )

    ratios = np.asarray(ratios)

    weighted_returns = np.asarray(
        weighted_returns
    )

    weight_sum = np.sum(ratios)

    if weight_sum == 0.0:
        raise ValueError(
            "All importance weights are zero."
        )

    estimate = (
        np.sum(weighted_returns)
        / weight_sum
    )

    return {
        "estimate": float(estimate),
        "ratios": ratios,
        "weighted_returns": weighted_returns,
    }


# ================================================================
# 10. PER-DECISION IMPORTANCE SAMPLING
# ================================================================

def per_decision_importance_sampling(
    dataset,
    target_p_action_1=TARGET_P_ACTION_1,
    behavior_p_action_1=BEHAVIOR_P_ACTION_1,
    gamma=GAMMA,
):
    """
    Per-Decision Importance Sampling:

        V_PDIS =
            (1/N) * sum[i]
            sum[t]
            gamma^t * rho_0:t * R_t

    Each reward is weighted only by the importance
    ratios up to the decision that generated it.

    This avoids multiplying an early reward by
    importance ratios from future actions.
    """

    if len(dataset) == 0:
        raise ValueError(
            "Dataset cannot be empty."
        )

    episode_estimates = []

    for trajectory in dataset:

        cumulative_ratio = 1.0

        episode_estimate = 0.0

        for t, (action, reward) in enumerate(
            zip(
                trajectory.actions,
                trajectory.rewards,
            )
        ):

            target_p = policy_probabilities(
                target_p_action_1
            )[action]

            behavior_p = policy_probabilities(
                behavior_p_action_1
            )[action]

            step_ratio = importance_ratio(
                target_p,
                behavior_p,
            )

            cumulative_ratio *= step_ratio

            episode_estimate += (
                (gamma ** t)
                * cumulative_ratio
                * reward
            )

        episode_estimates.append(
            episode_estimate
        )

    return {
        "estimate": float(
            np.mean(episode_estimates)
        ),
        "episode_estimates": np.asarray(
            episode_estimates
        ),
    }


# ================================================================
# 11. ON-POLICY MONTE CARLO ESTIMATION
# ================================================================

def on_policy_monte_carlo(
    num_episodes,
    target_p_action_1=TARGET_P_ACTION_1,
    seed=SEED,
    gamma=GAMMA,
):
    """
    Direct Monte Carlo evaluation.

    Data is generated using the target policy itself.

    No importance weights are needed.
    """

    env = FiniteHorizonEnvironment(
        seed=seed
    )

    action_probs = policy_probabilities(
        target_p_action_1
    )

    returns = []

    for _ in range(num_episodes):

        env.reset()

        rewards = []

        terminated = False

        while not terminated:

            action = int(
                env.rng.choice(
                    [0, 1],
                    p=action_probs,
                )
            )

            _, reward, terminated = env.step(
                action
            )

            rewards.append(reward)

        returns.append(
            calculate_discounted_return(
                rewards,
                gamma,
            )
        )

    return float(
        np.mean(returns)
    )


# ================================================================
# 12. EXACT TARGET-POLICY VALUE
# ================================================================

def exact_target_value(
    target_p_action_1=TARGET_P_ACTION_1,
    gamma=GAMMA,
):
    """
    Expected reward per step:

        E[R] =
            P(a=0)*0.2 + P(a=1)*0.8

    Exact expected return:

        V(pi) =
            E[R] * sum[t=0 to HORIZON-1] gamma^t
    """

    expected_reward = (
        (1.0 - target_p_action_1) * 0.2
        + target_p_action_1 * 0.8
    )

    return float(
        sum(
            (gamma ** t) * expected_reward
            for t in range(HORIZON)
        )
    )


# ================================================================
# 13. EFFECTIVE SAMPLE SIZE
# ================================================================

def effective_sample_size(weights):
    """
    Effective Sample Size:

        ESS = (sum w)^2 / sum(w^2)

    ESS approximates how many equally weighted samples
    would provide a similar amount of information.

    ESS is between 1 and N for nonzero nonnegative weights.
    """

    weights = np.asarray(
        weights,
        dtype=float,
    )

    if weights.ndim != 1:
        raise ValueError(
            "Weights must be one-dimensional."
        )

    if len(weights) == 0:
        raise ValueError(
            "Weights cannot be empty."
        )

    if np.any(weights < 0):
        raise ValueError(
            "Importance weights cannot be negative."
        )

    denominator = np.sum(
        weights ** 2
    )

    if denominator == 0:
        return 0.0

    return float(
        (np.sum(weights) ** 2)
        / denominator
    )


# ================================================================
# 14. SUPPORT VALIDATION
# ================================================================

def validate_policy_support(
    target_probabilities,
    behavior_probabilities,
):
    """
    Verify:

        pi(a) > 0  =>  b(a) > 0

    for every action.

    This is a necessary condition for importance
    sampling to evaluate the target policy.
    """

    target_probabilities = np.asarray(
        target_probabilities,
        dtype=float,
    )

    behavior_probabilities = np.asarray(
        behavior_probabilities,
        dtype=float,
    )

    if (
        target_probabilities.shape
        != behavior_probabilities.shape
    ):
        raise ValueError(
            "Policy probability shapes must match."
        )

    if not np.isclose(
        np.sum(target_probabilities),
        1.0,
    ):
        raise ValueError(
            "Target probabilities must sum to 1."
        )

    if not np.isclose(
        np.sum(behavior_probabilities),
        1.0,
    ):
        raise ValueError(
            "Behavior probabilities must sum to 1."
        )

    if np.any(target_probabilities < 0):
        raise ValueError(
            "Target probabilities cannot be negative."
        )

    if np.any(behavior_probabilities < 0):
        raise ValueError(
            "Behavior probabilities cannot be negative."
        )

    invalid = (
        (target_probabilities > 0)
        & (behavior_probabilities == 0)
    )

    if np.any(invalid):
        raise ValueError(
            "Support violation: behavior policy does not "
            "cover all target-policy actions."
        )

    return True


