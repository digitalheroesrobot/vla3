def visualize_convergence(results):

    sample_sizes = results[
        "sample_sizes"
    ]

    exact = results["exact"]

    fig, ax = plt.subplots(
        figsize=(10, 5)
    )

    for method, data in results[
        "methods"
    ].items():

        means = np.asarray(
            data["mean"]
        )

        stds = np.asarray(
            data["std"]
        )

        ax.plot(
            sample_sizes,
            means,
            marker="o",
            label=method,
        )

        ax.fill_between(
            sample_sizes,
            means - stds,
            means + stds,
            alpha=0.10,
        )

    ax.axhline(
        exact,
        linestyle="--",
        label="Exact value",
    )

    ax.set_xscale("log")

    ax.set_title(
        "Estimator Convergence vs Sample Size"
    )

    ax.set_xlabel(
        "Number of behavior-policy episodes"
    )

    ax.set_ylabel(
        "Estimated target-policy return"
    )

    ax.legend()

    ax.grid(True)

    fig.tight_layout()


