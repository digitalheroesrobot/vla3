def run_tests():

    print("\n========== UNIT TESTS ==========")

    # Test 1: Policy normalization.
    behavior = policy_probabilities(0.5)

    target = policy_probabilities(0.8)

    assert np.isclose(
        np.sum(behavior),
        1.0,
    )

    assert np.isclose(
        np.sum(target),
        1.0,
    )

    print("[PASS] Policy probability normalization")

    # Test 2: One-step importance ratio.
    #
    # Action 1:
    # 0.8 / 0.5 = 1.6

    ratio = importance_ratio(
        0.8,
        0.5,
    )

    assert np.isclose(
        ratio,
        1.6,
    )

    print("[PASS] One-step importance ratio")

    # Test 3: Zero target probability.
    #
    # 0 / 0.5 = 0

    ratio = importance_ratio(
        0.0,
        0.5,
    )

    assert ratio == 0.0

    print("[PASS] Zero target probability")

    # Test 4: Support violation.
    try:

        importance_ratio(
            0.5,
            0.0,
        )

        raise AssertionError(
            "Expected support violation."
        )

    except ValueError:
        pass

    print("[PASS] Support violation detection")

    # Test 5: Complete trajectory ratio.
    #
    # Actions = [1, 0, 1]
    #
    # Ratios = [1.6, 0.4, 1.6]
    #
    # Product = 1.024

    ratio = calculate_episode_importance_ratio(
        actions=[1, 0, 1],
    )

    assert np.isclose(
        ratio,
        1.024,
    )

    print("[PASS] Complete trajectory ratio")

    # Test 6: Trajectory ratio equals product.
    #
    # Direct calculation:
    #
    # (0.8/0.5) * (0.2/0.5) * (0.8/0.5)

    direct = (
        1.6 * 0.4 * 1.6
    )

    assert np.isclose(
        ratio,
        direct,
    )

    print("[PASS] Trajectory ratio multiplication")

    # Test 7: Discounted return.
    #
    # [1, 0, 1], gamma=0.9
    #
    # G = 1 + 0 + 0.81 = 1.81

    G = calculate_discounted_return(
        [1.0, 0.0, 1.0],
        gamma=0.9,
    )

    assert np.isclose(
        G,
        1.81,
    )

    print("[PASS] Discounted return")

    # Test 8: Ordinary IS hand calculation.
    #
    # One trajectory:
    # actions = [1, 0, 1]
    # rewards = [1, 0, 1]
    #
    # rho = 1.024
    #
    # G = 1.81
    #
    # OIS = 1.024 * 1.81

    trajectory = Trajectory(
        actions=[1, 0, 1],
        rewards=[1.0, 0.0, 1.0],
    )

    result = ordinary_importance_sampling(
        [trajectory],
        gamma=0.9,
    )

    assert np.isclose(
        result["estimate"],
        1.024 * 1.81,
    )

    print("[PASS] Ordinary IS hand calculation")

    # Test 9: Weighted IS with one trajectory.
    #
    # With one trajectory:
    # WIS = rho*G / rho = G

    result = weighted_importance_sampling(
        [trajectory],
        gamma=0.9,
    )

    assert np.isclose(
        result["estimate"],
        1.81,
    )

    print("[PASS] Weighted IS single trajectory")

    # Test 10: Per-decision IS.
    #
    # Actions = [1, 0, 1]
    # Rewards = [1, 0, 1]
    #
    # Step ratios:
    # [1.6, 0.4, 1.6]
    #
    # Cumulative ratios:
    # [1.6, 0.64, 1.024]
    #
    # PDIS:
    # 1.6*1
    # + 0.9*0.64*0
    # + 0.9^2*1.024*1
    #
    # = 2.42944

    result = per_decision_importance_sampling(
        [trajectory],
        gamma=0.9,
    )

    assert np.isclose(
        result["estimate"],
        2.42944,
    )

    print("[PASS] Per-decision IS")

    # Test 11: Effective sample size.
    #
    # Equal weights [1,1,1,1]:
    #
    # ESS = 4^2 / 4 = 4

    ess = effective_sample_size(
        np.ones(4)
    )

    assert np.isclose(
        ess,
        4.0,
    )

    print("[PASS] Effective sample size")

    # Test 12: ESS with unequal weights.
    #
    # [1,1,0,0]
    #
    # ESS = 2^2 / 2 = 2

    ess = effective_sample_size(
        np.array([1.0, 1.0, 0.0, 0.0])
    )

    assert np.isclose(
        ess,
        2.0,
    )

    print("[PASS] Unequal-weight ESS")

    # Test 13: Policy support.
    assert validate_policy_support(
        target_probabilities=[0.2, 0.8],
        behavior_probabilities=[0.5, 0.5],
    )

    print("[PASS] Policy support validation")

    # Test 14: Invalid support.
    try:

        validate_policy_support(
            target_probabilities=[0.2, 0.8],
            behavior_probabilities=[1.0, 0.0],
        )

        raise AssertionError(
            "Expected support violation."
        )

    except ValueError:
        pass

    print("[PASS] Policy support rejection")

    # Test 15: Exact expected target value.
    #
    # Expected reward = 0.68
    #
    # V = 0.68*(1 + 0.95 + 0.95^2)

    exact = exact_target_value()

    expected = (
        0.68
        * (
            1.0
            + 0.95
            + 0.95 ** 2
        )
    )

    assert np.isclose(
        exact,
        expected,
    )

    print("[PASS] Exact target-policy value")

    # Test 16: Environment reward validity.

    env = FiniteHorizonEnvironment(
        seed=1
    )

    env.reset()

    _, reward, _ = env.step(1)

    assert reward in (0.0, 1.0)

    print("[PASS] Environment reward")

    # Test 17: Generated dataset structure.

    dataset = generate_dataset(
        num_episodes=20,
        seed=123,
    )

    assert len(dataset) == 20

    for episode in dataset:

        assert episode.length == HORIZON

        assert len(episode.actions) == len(
            episode.rewards
        )

        assert all(
            action in (0, 1)
            for action in episode.actions
        )

        assert all(
            reward in (0.0, 1.0)
            for reward in episode.rewards
        )

    print("[PASS] Generated dataset structure")

    # Test 18: All estimators return finite values.

    test_dataset = generate_dataset(
        num_episodes=1000,
        seed=456,
    )

    ois = ordinary_importance_sampling(
        test_dataset
    )

    wis = weighted_importance_sampling(
        test_dataset
    )

    pdis = per_decision_importance_sampling(
        test_dataset
    )

    assert np.isfinite(ois["estimate"])

    assert np.isfinite(wis["estimate"])

    assert np.isfinite(pdis["estimate"])

    print("[PASS] Estimator numerical stability")

    # Test 19: Exact value lies within reward bounds.

    exact = exact_target_value()

    maximum_return = sum(
        GAMMA ** t
        for t in range(HORIZON)
    )

    assert 0.0 <= exact <= maximum_return

    print("[PASS] Exact value bounds")

    # Test 20: On-policy estimator.

    on_policy = on_policy_monte_carlo(
        num_episodes=5000,
        seed=789,
    )

    assert np.isfinite(on_policy)

    assert abs(
        on_policy - exact_target_value()
    ) < 0.15

    print("[PASS] On-policy Monte Carlo")

    print("\nAll 20 tests passed.")


