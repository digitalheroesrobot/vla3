# 10. NUMERICAL METRICS
# ============================================================

def rmse(
    estimated,
    reference,
    exclude_terminal=True
):

    estimated = np.asarray(estimated)
    reference = np.asarray(reference)

    if exclude_terminal:

        mask = np.ones(
            len(reference),
            dtype=bool
        )

        mask[GOAL_STATE] = False

        estimated = estimated[mask]
        reference = reference[mask]

    return float(
        np.sqrt(
            np.mean(
                (estimated - reference) ** 2
            )
        )
    )


def moving_average(values, window=100):

    values = np.asarray(
        values,
        dtype=float
    )

    if len(values) < window:
        return values

    kernel = np.ones(window) / window

    return np.convolve(
        values,
        kernel,
        mode="valid"
    )


