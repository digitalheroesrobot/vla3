import numpy as np
import matplotlib.pyplot as plt


# ============================================================
# 1. CONFIGURATION
# ============================================================

SEED = 42
GAMMA = 0.95

ROWS = 4
COLS = 4

START_STATE = 0
GOAL_STATE = ROWS * COLS - 1

NUM_STATES = ROWS * COLS
NUM_ACTIONS = 4

ACTION_NAMES = {
    0: "UP",
    1: "DOWN",
    2: "LEFT",
    3: "RIGHT",
}

ACTION_SYMBOLS = {
    0: "↑",
    1: "↓",
    2: "←",
    3: "→",
}


# ============================================================
# 2. GRIDWORLD ENVIRONMENT
# ============================================================

@dataclass
class StepResult:
    next_state: int
    reward: float
    terminated: bool
    truncated: bool


class GridWorld:
    """
    Deterministic episodic GridWorld.

    State:
        Integer from 0 to NUM_STATES - 1.

    Action:
        0 = Up
        1 = Down
        2 = Left
        3 = Right

    Reward:
        -1 for ordinary movement.
        +10 when entering the goal.

    Moving outside the grid leaves the agent in place.
    Reaching the goal terminates the episode.
    """

    def __init__(self):
        self.rows = ROWS
        self.cols = COLS
        self.start_state = START_STATE
        self.goal_state = GOAL_STATE
        self.state = self.start_state

    def reset(self):
        self.state = self.start_state
        return self.state

    def is_terminal(self, state):
        return state == self.goal_state

    def step(self, action):

        if self.is_terminal(self.state):
            raise RuntimeError("Cannot step after termination.")

        row = self.state // self.cols
        col = self.state % self.cols

        if action == 0:
            row -= 1
        elif action == 1:
            row += 1
        elif action == 2:
            col -= 1
        elif action == 3:
            col += 1
        else:
            raise ValueError("Invalid action.")

        row = int(np.clip(row, 0, self.rows - 1))
        col = int(np.clip(col, 0, self.cols - 1))

        next_state = row * self.cols + col

        if next_state == self.goal_state:
            reward = 10.0
            terminated = True
        else:
            reward = -1.0
            terminated = False

        self.state = next_state

        return StepResult(
            next_state=next_state,
            reward=reward,
            terminated=terminated,
            truncated=False,
        )


