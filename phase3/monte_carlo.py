def visualize_value_comparison(
    exact_values,
    first_visit_values,
    every_visit_values
):

    matrices = [
        exact_values.reshape(ROWS, COLS),
        first_visit_values.reshape(ROWS, COLS),
        every_visit_values.reshape(ROWS, COLS),
    ]

    titles = [
        "Exact DP V(s)",
        "First-Visit MC",
        "Every-Visit MC",
    ]

    fig, axes = plt.subplots(
        1, 3,
        figsize=(15, 5)
    )

    for ax, matrix, title in zip(
        axes,
        matrices,
        titles
    ):

        image = ax.imshow(matrix)

        ax.set_title(title)
        ax.set_xticks(range(COLS))
        ax.set_yticks(range(ROWS))

        for row in range(ROWS):
            for col in range(COLS):

                ax.text(
                    col,
                    row,
                    f"{matrix[row, col]:.1f}",
                    ha="center",
                    va="center"
                )

        fig.colorbar(
            image,
            ax=ax,
            fraction=0.046
        )

    fig.suptitle(
        "Monte Carlo Prediction vs Exact Reference"
    )

    plt.tight_layout()


