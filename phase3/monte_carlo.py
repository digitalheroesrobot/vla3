# 9. OFF-POLICY IMPORTANCE SAMPLING
# ============================================================

def importance_ratio(
    target_probability,
    behavior_probability
):
    """
    One-step importance ratio:

        rho = pi(a|s) / b(a|s)

    If b(a|s) = 0 and pi(a|s) > 0:
        Return infinity.

    Such a sample cannot legitimately occur under the
    behavior policy. It signals a coverage violation.

    If both probabilities are zero:
        Return zero by implementation convention.
        This is not a valid sampled action under b.
    """

    if behavior_probability < 0.0:
        raise ValueError(
            "Behavior probability cannot be negative."
        )

    if target_probability < 0.0:
        raise ValueError(
            "Target probability cannot be negative."
        )

    if behavior_probability == 0.0:

        if target_probability == 0.0:
            return 0.0

        return np.inf

    return target_probability / behavior_probability


def off_policy_importance_sampling_demo(
    num_episodes=30000,
    seed=SEED
):
    """
    One-step episodic example.

    One state, two actions.

    Rewards:
        Action 0 -> 1
        Action 1 -> 5

    Target policy:
        pi(0) = 0.8
        pi(1) = 0.2

    Behavior policy:
        b(0) = 0.5
        b(1) = 0.5

    True target value:

        V_pi = 0.8*1 + 0.2*5 = 1.8

    Ordinary importance sampling:

        mean(rho_i * G_i)

    Weighted importance sampling:

        sum(rho_i * G_i) / sum(rho_i)
    """

    rng = np.random.default_rng(seed)

    target_policy = np.array([0.8, 0.2])
    behavior_policy = np.array([0.5, 0.5])

    action_rewards = np.array([1.0, 5.0])

    true_value = float(
        np.dot(
            target_policy,
            action_rewards
        )
    )

    ordinary_estimates = []
    weighted_estimates = []

    weighted_numerator = 0.0
    weighted_denominator = 0.0

    ordinary_sum = 0.0

    for episode in range(1, num_episodes + 1):

        action = sample_action(
            behavior_policy,
            rng
        )

        reward = action_rewards[action]

        rho = importance_ratio(
            target_policy[action],
            behavior_policy[action]
        )

        ordinary_sum += rho * reward

        weighted_numerator += rho * reward
        weighted_denominator += rho

        ordinary_estimates.append(
            ordinary_sum / episode
        )

        weighted_estimates.append(
            weighted_numerator / weighted_denominator
        )

    return {
        "true_value": true_value,
        "ordinary": np.asarray(ordinary_estimates),
        "weighted": np.asarray(weighted_estimates),
        "target_policy": target_policy,
        "behavior_policy": behavior_policy,
    }


def trajectory_importance_ratio(
    episode,
    target_policy,
    behavior_policy
):
    """
    Full trajectory importance ratio:

        rho_0:T-1 =
            product_t pi(A_t|S_t) / b(A_t|S_t)

    Log-space computation:

        log(rho) =
            sum_t [
                log pi(A_t|S_t)
                - log b(A_t|S_t)
            ]

    This reduces premature numerical overflow.

    If target probability is zero for a sampled action,
    the full ratio is zero.

    If behavior probability is zero for a sampled action,
    the trajectory is invalid under b and raises an error.
    """

    log_ratio = 0.0

    for transition in episode:

        state = transition[0]
        action = transition[1]

        pi_probability = target_policy[state, action]
        b_probability = behavior_policy[state, action]

        if b_probability <= 0.0:
            raise ValueError(
                "Sampled action has zero behavior probability."
            )

        if pi_probability <= 0.0:
            return 0.0

        log_ratio += (
            np.log(pi_probability)
            - np.log(b_probability)
        )

    if log_ratio > 700:
        return np.inf

    if log_ratio < -745:
        return 0.0

    return float(np.exp(log_ratio))


