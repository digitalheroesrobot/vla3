def visualize_learned_policy(policy):

    symbols = np.full(
        (ROWS, COLS),
        "",
        dtype=object
    )

    for state in range(NUM_STATES):

        row = state // COLS
        col = state % COLS

        if state == GOAL_STATE:
            symbols[row, col] = "G"
            continue

        best_actions = np.flatnonzero(
            np.isclose(
                policy[state],
                np.max(policy[state])
            )
        )

        symbols[row, col] = "".join(
            ACTION_SYMBOLS[action]
            for action in best_actions
        )

    plt.figure(figsize=(6, 6))

    plt.imshow(
        np.zeros((ROWS, COLS))
    )

    plt.xticks(range(COLS))
    plt.yticks(range(ROWS))
    plt.grid(True)

    for row in range(ROWS):
        for col in range(COLS):

            plt.text(
                col,
                row,
                symbols[row, col],
                ha="center",
                va="center",
                fontsize=18
            )

    plt.title(
        "Greedy Policy Learned by MC Control"
    )

    plt.tight_layout()


