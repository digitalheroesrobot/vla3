def run_tests():

    print("\n========== UNIT TESTS ==========")

    # Test 1: Discounted return calculation.
    rewards = [1.0, 2.0, 3.0]

    returns = calculate_returns(
        rewards,
        0.5
    )

    expected = np.array([
        2.75,
        3.5,
        3.0
    ])

    assert np.allclose(
        returns,
        expected
    )

    print("[PASS] Discounted return calculation")

    # Test 2: Epsilon-greedy probabilities.
    probabilities = epsilon_greedy_probabilities(
        np.array([1.0, 3.0, 3.0, 0.0]),
        epsilon=0.2
    )

    assert np.isclose(
        probabilities.sum(),
        1.0
    )

    assert np.isclose(
        probabilities[1],
        probabilities[2]
    )

    assert probabilities[1] > probabilities[0]

    print("[PASS] Epsilon-greedy probabilities")

    # Test 3: First-visit vs every-visit counting.
    #
    # State 0 appears at t=0 and t=2.
    # Returns are [4, 3, 2].
    #
    # First-visit records [4].
    # Every-visit records [4, 2].

    repeated_episode = [
        (0, 0, 1.0, 1, False),
        (1, 0, 1.0, 0, False),
        (0, 1, 2.0, 2, True),
    ]

    returns = calculate_returns(
        [1.0, 1.0, 2.0],
        1.0
    )

    first_visit_returns = {}
    every_visit_returns = {}

    visited = set()

    for t, transition in enumerate(repeated_episode):

        state = transition[0]

        every_visit_returns.setdefault(
            state,
            []
        ).append(returns[t])

        if state not in visited:

            first_visit_returns.setdefault(
                state,
                []
            ).append(returns[t])

            visited.add(state)

    assert first_visit_returns[0] == [4.0]
    assert every_visit_returns[0] == [4.0, 2.0]

    assert np.isclose(
        np.mean(every_visit_returns[0]),
        3.0
    )

    print("[PASS] First-visit and every-visit counting")

    # Test 4: Incremental sample average.
    value = 0.0

    samples = [2.0, 4.0, 6.0]

    for count, target in enumerate(
        samples,
        start=1
    ):

        value += (
            target - value
        ) / count

    assert np.isclose(value, 4.0)

    print("[PASS] Incremental sample-average update")

    # Test 5: Constant-step-size update.
    value = 0.0
    alpha = 0.5

    value += alpha * (2.0 - value)
    value += alpha * (4.0 - value)

    assert np.isclose(value, 2.5)

    print("[PASS] Constant-step-size update")

    # Test 6: Importance sampling ratio.
    rho = importance_ratio(
        target_probability=0.8,
        behavior_probability=0.5
    )

    assert np.isclose(rho, 1.6)

    print("[PASS] Importance sampling ratio")

    # Test 7: Zero target-policy probability.
    rho = importance_ratio(
        target_probability=0.0,
        behavior_probability=0.5
    )

    assert rho == 0.0

    print("[PASS] Zero target-policy probability")

    # Test 8: Zero behavior probability.
    #
    # b(a|s) = 0 and pi(a|s) > 0:
    # importance ratio is infinite.
    #
    # This indicates a coverage violation. Such an action
    # cannot legitimately be sampled from the behavior policy.

    rho = importance_ratio(
        target_probability=0.5,
        behavior_probability=0.0
    )

    assert np.isinf(rho)

    # If both probabilities are zero, this implementation
    # returns zero by convention. This is not a valid sample.

    rho = importance_ratio(
        target_probability=0.0,
        behavior_probability=0.0
    )

    assert rho == 0.0

    print("[PASS] Zero behavior probability handling")

    # Test 9: Full trajectory importance ratio.
    episode = [
        (0, 0, 1.0, 1, False),
        (1, 1, 2.0, 2, True),
    ]

    target = np.array([
        [0.8, 0.2],
        [0.4, 0.6],
    ])

    behavior = np.array([
        [0.5, 0.5],
        [0.5, 0.5],
    ])

    rho = trajectory_importance_ratio(
        episode,
        target,
        behavior
    )

    expected_rho = (
        (0.8 / 0.5) *
        (0.6 / 0.5)
    )

    assert np.isclose(
        rho,
        expected_rho
    )

    print("[PASS] Full trajectory importance ratio")

    # Test 10: Terminal value.
    policy = uniform_policy(
        NUM_STATES,
        NUM_ACTIONS
    )

    values = exact_policy_evaluation(
        policy,
        GAMMA
    )

    assert values[GOAL_STATE] == 0.0

    print("[PASS] Terminal state value")

    # Test 11: Exact Bellman equation.
    env = GridWorld()

    P, R = build_exact_transition_model(env)

    P_pi = np.einsum(
        "sa,san->sn",
        policy,
        P
    )

    r_pi = np.sum(
        policy * R,
        axis=1
    )

    bellman_values = (
        r_pi + GAMMA * P_pi @ values
    )

    nonterminal = np.arange(
        NUM_STATES - 1
    )

    assert np.allclose(
        values[nonterminal],
        bellman_values[nonterminal],
        atol=1e-9
    )

    print("[PASS] Exact Bellman equation")

    # Test 12: Goal transition.
    env.reset()

    env.state = GOAL_STATE - 1

    result = env.step(3)

    assert result.next_state == GOAL_STATE
    assert result.terminated
    assert result.reward == 10.0

    print("[PASS] GridWorld terminal transition")

    # Test 13: Boundary behavior.
    env.reset()

    result = env.step(0)

    assert result.next_state == START_STATE
    assert result.reward == -1.0

    print("[PASS] GridWorld boundary behavior")

    # Test 14: Policy probability normalization.
    assert np.allclose(
        policy.sum(axis=1),
        1.0
    )

    print("[PASS] Policy probability normalization")

    # Test 15: Analytical target-policy value.
    target_policy = np.array([0.8, 0.2])
    action_rewards = np.array([1.0, 5.0])

    true_value = np.dot(
        target_policy,
        action_rewards
    )

    assert np.isclose(
        true_value,
        1.8
    )

    print("[PASS] Target-policy expected value")

    print("\nAll 15 tests passed.")


