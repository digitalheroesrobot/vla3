# 3. POLICY FUNCTIONS
# ============================================================

def uniform_policy(num_states, num_actions):
    """
    Uniform stochastic policy:

        pi(a|s) = 1 / number_of_actions
    """

    return np.ones(
        (num_states, num_actions),
        dtype=float
    ) / num_actions


def epsilon_greedy_probabilities(q_values, epsilon):
    """
    Epsilon-greedy action probabilities.

    With probability 1-epsilon:
        Choose uniformly among greedy actions.

    With probability epsilon:
        Explore uniformly among all actions.

    Tied greedy actions share the exploitation probability.
    """

    q_values = np.asarray(q_values, dtype=float)

    if q_values.ndim != 1:
        raise ValueError("q_values must be one-dimensional.")

    if not 0.0 <= epsilon <= 1.0:
        raise ValueError("epsilon must be between 0 and 1.")

    num_actions = len(q_values)

    if num_actions == 0:
        raise ValueError("At least one action is required.")

    greedy_actions = np.flatnonzero(
        np.isclose(q_values, np.max(q_values))
    )

    probabilities = np.full(
        num_actions,
        epsilon / num_actions,
        dtype=float
    )

    probabilities[greedy_actions] += (
        (1.0 - epsilon) / len(greedy_actions)
    )

    return probabilities


def sample_action(probabilities, rng):

    probabilities = np.asarray(
        probabilities,
        dtype=float
    )

    if np.any(probabilities < 0):
        raise ValueError("Probabilities cannot be negative.")

    if not np.isclose(probabilities.sum(), 1.0):
        raise ValueError("Probabilities must sum to one.")

    return int(
        rng.choice(
            len(probabilities),
            p=probabilities
        )
    )


def linear_epsilon_decay(
    episode,
    initial_epsilon=1.0,
    final_epsilon=0.05,
    decay_episodes=5000
):
    """
    Linear exploration schedule:

        epsilon(e) =
            max(
                final_epsilon,
                initial_epsilon
                - e * (initial_epsilon-final_epsilon)
                  / decay_episodes
            )
    """

    fraction = min(
        episode / decay_episodes,
        1.0
    )

    return max(
        final_epsilon,
        initial_epsilon
        - fraction * (
            initial_epsilon - final_epsilon
        )
    )


# ============================================================
# 4. EPISODE GENERATION
# ============================================================

# Each transition is:
#
# (state, action, reward, next_state, terminated)
#
# A complete episode ends at the goal.
#
# If max_steps is reached first, the episode is incomplete.
# Standard MC updates below discard incomplete episodes.

def generate_episode(
    env,
    policy,
    rng,
    max_steps=500
):

    state = env.reset()
    episode = []

    for _ in range(max_steps):

        probabilities = policy(state)

        action = sample_action(
            probabilities,
            rng
        )

        result = env.step(action)

        episode.append(
            (
                state,
                action,
                result.reward,
                result.next_state,
                result.terminated,
            )
        )

        state = result.next_state

        if result.terminated:
            return episode, True

        if result.truncated:
            return episode, False

    return episode, False


# ============================================================
# 5. RETURN CALCULATION
# ============================================================

def calculate_returns(rewards, gamma):
    """
    Discounted return:

        G_t = R_(t+1)
              + gamma * R_(t+2)
              + gamma^2 * R_(t+3)
              + ...

    Backward recursion:

        G_t = R_(t+1) + gamma * G_(t+1)

    This computes all returns in O(T) time.
    """

    if not 0.0 <= gamma <= 1.0:
        raise ValueError("gamma must be between 0 and 1.")

    returns = np.zeros(
        len(rewards),
        dtype=float
    )

    running_return = 0.0

    for t in reversed(range(len(rewards))):

        running_return = (
            rewards[t] + gamma * running_return
        )

        returns[t] = running_return

    return returns


# ============================================================
# 6. MONTE CARLO PREDICTION
# ============================================================

def monte_carlo_prediction(
    env,
    policy,
    num_episodes,
    gamma,
    visit_mode="first",
    update_mode="sample_average",
    alpha=0.05,
    seed=SEED,
):
    """
    Estimate V_pi(s) using sampled complete episodes.

    First-visit MC:
        Update a state only at its first occurrence
        in the current episode.

    Every-visit MC:
        Update a state at every occurrence.

    Sample-average update:

        V(s) <- V(s) + [G - V(s)] / N(s)

    Constant-step-size update:

        V(s) <- V(s) + alpha * [G - V(s)]

    No transition model is used for learning.

    Incomplete episodes are discarded because their complete
    Monte Carlo returns are unavailable.
    """

    if visit_mode not in ("first", "every"):
        raise ValueError(
            "visit_mode must be 'first' or 'every'."
        )

    if update_mode not in (
        "sample_average",
        "constant"
    ):
        raise ValueError(
            "update_mode must be 'sample_average' or 'constant'."
        )

    rng = np.random.default_rng(seed)

    values = np.zeros(
        NUM_STATES,
        dtype=float
    )

    counts = np.zeros(
        NUM_STATES,
        dtype=int
    )

    completed_episodes = 0

    for _ in range(num_episodes):

        trajectory, complete = generate_episode(
            env,
            policy,
            rng
        )

        if not complete:
            continue

        completed_episodes += 1

        rewards = [
            transition[2]
            for transition in trajectory
        ]

        returns = calculate_returns(
            rewards,
            gamma
        )

        visited_states = set()

        for t, transition in enumerate(trajectory):

            state = transition[0]

            if state == env.goal_state:
                continue

            if visit_mode == "first":

                if state in visited_states:
                    continue

                visited_states.add(state)

            target = returns[t]

            counts[state] += 1

            if update_mode == "sample_average":

                values[state] += (
                    target - values[state]
                ) / counts[state]

            else:

                values[state] += (
                    alpha * (target - values[state])
                )

    return {
        "values": values,
        "counts": counts,
        "completed_episodes": completed_episodes,
    }


# ============================================================
# 7. EXACT POLICY EVALUATION — REFERENCE ONLY
# ============================================================

def build_exact_transition_model(env):
    """
    Construct P and R for the DP reference.

    P[s,a,s_next] = transition probability.
    R[s,a] = expected immediate reward.

    These arrays are used only for numerical verification.
    MC prediction does not use them.
    """

    P = np.zeros(
        (NUM_STATES, NUM_ACTIONS, NUM_STATES),
        dtype=float
    )

    R = np.zeros(
        (NUM_STATES, NUM_ACTIONS),
        dtype=float
    )

    for state in range(NUM_STATES):

        if state == env.goal_state:
            P[state, :, state] = 1.0
            R[state, :] = 0.0
            continue

        for action in range(NUM_ACTIONS):

            row = state // COLS
            col = state % COLS

            next_row = row
            next_col = col

            if action == 0:
                next_row -= 1
            elif action == 1:
                next_row += 1
            elif action == 2:
                next_col -= 1
            elif action == 3:
                next_col += 1

            next_row = int(
                np.clip(next_row, 0, ROWS - 1)
            )

            next_col = int(
                np.clip(next_col, 0, COLS - 1)
            )

            next_state = (
                next_row * COLS + next_col
            )

            P[state, action, next_state] = 1.0

            R[state, action] = (
                10.0
                if next_state == env.goal_state
                else -1.0
            )

    return P, R


def exact_policy_evaluation(policy, gamma):
    """
    Solve the Bellman expectation equation:

        V_pi = r_pi + gamma * P_pi * V_pi

    Rearrangement:

        (I - gamma * P_pi) V_pi = r_pi

    Solve the linear system directly with numpy.linalg.solve.
    The terminal state's value is fixed at zero.
    """

    env = GridWorld()

    P, R = build_exact_transition_model(env)

    P_pi = np.einsum(
        "sa,san->sn",
        policy,
        P
    )

    r_pi = np.sum(
        policy * R,
        axis=1
    )

    nonterminal = np.array([
        state
        for state in range(NUM_STATES)
        if state != GOAL_STATE
    ])

    P_reduced = P_pi[
        np.ix_(nonterminal, nonterminal)
    ]

    r_reduced = r_pi[nonterminal]

    identity = np.eye(len(nonterminal))

    values_reduced = np.linalg.solve(
        identity - gamma * P_reduced,
        r_reduced
    )

    values = np.zeros(
        NUM_STATES,
        dtype=float
    )

    values[nonterminal] = values_reduced

    return values


# ============================================================
# 8. MONTE CARLO CONTROL
# ============================================================

def monte_carlo_control(
    num_episodes=12000,
    gamma=GAMMA,
    seed=SEED,
    max_steps=500,
):
    """
    On-policy epsilon-soft Monte Carlo control.

    Learn action values:

        Q(s,a) = expected return after taking action a
                 in state s and following the policy.

    Incremental sample-average update:

        Q(s,a) <- Q(s,a)
                  + [G - Q(s,a)] / N(s,a)

    The behavior policy is epsilon-greedy with respect
    to the current Q estimates.

    First-visit state-action updates are used.
    """

    env = GridWorld()
    rng = np.random.default_rng(seed)

    q_values = np.zeros(
        (NUM_STATES, NUM_ACTIONS),
        dtype=float
    )

    counts = np.zeros(
        (NUM_STATES, NUM_ACTIONS),
        dtype=int
    )

    rewards_history = []
    lengths_history = []
    epsilon_history = []

    completed_episodes = 0

    for episode_index in range(num_episodes):

        epsilon = linear_epsilon_decay(
            episode_index,
            initial_epsilon=1.0,
            final_epsilon=0.05,
            decay_episodes=8000
        )

        epsilon_history.append(epsilon)

        def current_policy(state):
            return epsilon_greedy_probabilities(
                q_values[state],
                epsilon
            )

        trajectory, complete = generate_episode(
            env,
            current_policy,
            rng,
            max_steps=max_steps
        )

        if not complete:
            continue

        completed_episodes += 1

        rewards = [
            transition[2]
            for transition in trajectory
        ]

        returns = calculate_returns(
            rewards,
            gamma
        )

        visited_state_actions = set()

        for t, transition in enumerate(trajectory):

            state = transition[0]
            action = transition[1]

            key = (state, action)

            if key in visited_state_actions:
                continue

            visited_state_actions.add(key)

            counts[state, action] += 1

            q_values[state, action] += (
                returns[t] - q_values[state, action]
            ) / counts[state, action]

        rewards_history.append(sum(rewards))
        lengths_history.append(len(trajectory))

    # Extract a greedy policy from learned Q values.
    greedy_policy = np.zeros(
        (NUM_STATES, NUM_ACTIONS),
        dtype=float
    )

    for state in range(NUM_STATES):

        if state == GOAL_STATE:
            greedy_policy[state] = 0.25
            continue

        greedy_actions = np.flatnonzero(
            np.isclose(
                q_values[state],
                np.max(q_values[state])
            )
        )

        greedy_policy[state, greedy_actions] = (
            1.0 / len(greedy_actions)
        )

    return {
        "q_values": q_values,
        "counts": counts,
        "policy": greedy_policy,
        "rewards": np.asarray(rewards_history),
        "lengths": np.asarray(lengths_history),
        "epsilon": np.asarray(epsilon_history),
        "completed_episodes": completed_episodes,
    }


